class Command(BaseCommand):
    help = "Seed original PMI ECO-aligned production practice questions for thin domains."

    @transaction.atomic
    def handle(self, *args, **options):
        created = 0
        for item in QUESTIONS:
            domain, _ = PMPDomain.objects.get_or_create(name=item["domain"])
            topic, _ = PMPTopic.objects.get_or_create(domain=domain, name=item["topic"])
            question, made = PMPQuestion.objects.get_or_create(
                question_id=item["question_id"],
                defaults={
                    "question_text": item["text"],
                    "domain": domain,
                    "topic": topic,
                    "performance_domain": item["domain"],
                    "eco_domain": item["eco_domain"],
                    "eco_task": item["topic"],
                    "task": item["topic"],
                    "methodology": item["methodology"],
                    "difficulty": item["difficulty"],
                    "question_type": "Single Response",
                    "correct_answer_explanation": item["explanation"],
                    "wrong_answer_explanation": "Distractors either skip impact analysis, bypass governance, ignore stakeholder engagement, or choose action before understanding the scenario.",
                    "pmp_reference": SOURCE_REFERENCE,
                    "chapter_reference": item["topic"],
                    "source_file": SOURCE_FILE,
                    "source_sheet": item["domain"],
                    "source_year": 2026,
                    "source_item_id": item["question_id"],
                    "is_active": True,
                    "is_synthetic": False,
                },
            )
            if not made:
                continue
            PMPQuestionOption.objects.bulk_create([
                PMPQuestionOption(
                    question=question,
                    option_label=chr(65 + index),
                    option_text=option,
                    is_correct=option == item["correct"],
                )
                for index, option in enumerate(item["options"])
            ])
            created += 1
        self.stdout.write(self.style.SUCCESS(f"Seeded {created} official-aligned original questions."))
